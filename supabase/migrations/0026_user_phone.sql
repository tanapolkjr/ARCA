-- =============================================================================
-- 0026 — เบอร์โทรของผู้ขาย
--
-- ลูกค้าที่ได้ใบเสนอราคาต้องโทรกลับหาเซลล์คนที่ออกใบให้ได้
-- เก็บที่ผู้ใช้ ไม่ใช่ที่เอกสาร เพราะเป็นข้อมูลของคน ไม่ใช่ของเอกสารแต่ละใบ
-- (เอกสารเก็บ snapshot ของบริษัทและลูกค้าเท่านั้น เบอร์เซลล์เปลี่ยนแล้วใบเก่า
--  ควรขึ้นเบอร์ปัจจุบัน ลูกค้าจะได้โทรติด)
--
-- Idempotent. รันก่อน deploy โค้ด
-- =============================================================================

alter table public.users
  add column if not exists phone varchar(50);

comment on column public.users.phone is
  'เบอร์โทรของผู้ใช้ — พิมพ์บนเอกสารใต้ชื่อผู้ขาย ให้ลูกค้าโทรกลับได้';
